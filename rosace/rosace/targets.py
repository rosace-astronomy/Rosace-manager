"""
Target database (stars) and scientific programs.
File: ~/.rosace/databases/targets.db
"""

import logging
import re
from typing import Optional

import aiosqlite
from pydantic import BaseModel, Field, field_validator

from .config import DATABASES_DIR

log = logging.getLogger("spectro.targets")

TARGETS_DB_PATH = DATABASES_DIR / "targets.db"

# A program name ends up interpolated as-is into a file path and a dynamically
# imported Python module path (plugins/pipeline_loader.py) — restricted to the
# characters a path/module component can legitimately take (no '-', invalid in
# a Python identifier), to prevent any directory traversal (e.g. "../../etc").
_PROGRAM_NAME_RE = re.compile(r"^[A-Za-z0-9_]+$")

# ─────────────────────────────────────────────────────────────
# Models
# ─────────────────────────────────────────────────────────────

class StarCreate(BaseModel):
    """Fields provided by the user when creating a star."""
    name: str
    ra: float = Field(..., ge=0, lt=360, description="Right ascension in degrees")
    dec: float = Field(..., ge=-90, le=90, description="Declination in degrees")
    magnitude_v: Optional[float] = None
    spectral_type: Optional[str] = None
    notes: Optional[str] = None

class Star(StarCreate):
    """Star as returned by the API (with an id generated by SQLite)."""
    id: int


class ProgramCreate(BaseModel):
    """Fields provided by the user when creating a program."""
    name: str
    description: Optional[str] = None

    @field_validator("name")
    @classmethod
    def _validate_name(cls, v: str) -> str:
        if not _PROGRAM_NAME_RE.fullmatch(v):
            log.warning(f"[PROGRAMS] Program name rejected: {v!r} — allowed characters: letters, digits, '_'")
            raise ValueError("the name can only contain letters, digits and '_'")
        return v

class Program(ProgramCreate):
    """Program as returned by the API (with an id generated by SQLite)."""
    id: int


class StarInProgram(Star):
    """Star as listed within a program, with its exposure time, optionally
    specific to this program (optional — if absent, derived from
    magnitude_v at acquisition time)."""
    exposure_time: Optional[float] = None


class StarLookup(Star):
    """Star as returned by a name lookup: keeps the requested name
    (queried_name) alongside the canonical name (name) — kept separate,
    not merged into a single display string, so both stay reusable as-is
    in a later request."""
    queried_name: str


# ─────────────────────────────────────────────────────────────
# Initialization
# ─────────────────────────────────────────────────────────────

async def targets_db_init() -> None:
    """Creates the tables if they don't already exist."""
    DATABASES_DIR.mkdir(parents=True, exist_ok=True)
    async with aiosqlite.connect(TARGETS_DB_PATH, timeout=30.0) as db:
        # WAL: a bulk import (several seconds, sequential Simbad calls) is no
        # longer blocked by a concurrent read (GUI, polling...).
        await db.execute("PRAGMA journal_mode=WAL")
        await db.execute("""
            CREATE TABLE IF NOT EXISTS stars (
                id            INTEGER PRIMARY KEY AUTOINCREMENT,
                name          TEXT NOT NULL,
                ra            REAL NOT NULL,
                dec           REAL NOT NULL,
                magnitude_v   REAL,
                spectral_type TEXT,
                notes         TEXT
            )
        """)
        await db.execute("""
            CREATE TABLE IF NOT EXISTS star_aliases (
                id         INTEGER PRIMARY KEY AUTOINCREMENT,
                star_id    INTEGER NOT NULL REFERENCES stars(id),
                alias_name TEXT NOT NULL UNIQUE
            )
        """)
        await db.execute("""
            CREATE TABLE IF NOT EXISTS programs (
                id          INTEGER PRIMARY KEY AUTOINCREMENT,
                name        TEXT NOT NULL,
                description TEXT
            )
        """)
        await db.execute("""
            CREATE TABLE IF NOT EXISTS program_stars (
                program_id    INTEGER NOT NULL REFERENCES programs(id),
                star_id       INTEGER NOT NULL REFERENCES stars(id),
                exposure_time REAL,
                PRIMARY KEY (program_id, star_id)
            )
        """)
        await db.commit()
    log.info(f"[TARGETS DB] Database initialised: {TARGETS_DB_PATH}")



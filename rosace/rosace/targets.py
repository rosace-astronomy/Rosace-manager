async def star_add_alias(star_id: int, alias_name: str) -> int:
    """Adds an alternate name for a star and returns the alias's id.
    alias_name must be unique across the whole database (one star per alias)."""
    async with aiosqlite.connect(TARGETS_DB_PATH, timeout=30.0) as db:
        cursor = await db.execute(
            "INSERT INTO star_aliases (star_id, alias_name) VALUES (?, ?)",
            (star_id, alias_name)
        )
        await db.commit()
        log.info(f"[TARGETS DB] Alias added: {alias_name} -> star_id={star_id}")
        return cursor.lastrowid


async def star_remove_alias(alias_id: int) -> None:
    """Deletes an alias by its id."""
    async with aiosqlite.connect(TARGETS_DB_PATH, timeout=30.0) as db:
        await db.execute("DELETE FROM star_aliases WHERE id = ?", (alias_id,))
        await db.commit()
    log.info(f"[TARGETS DB] Alias deleted: id={alias_id}")


async def star_list_aliases(star_id: int) -> list[str]:
    """Returns every known alternate name for a star."""
    async with aiosqlite.connect(TARGETS_DB_PATH, timeout=30.0) as db:
        db.row_factory = aiosqlite.Row
        async with db.execute(
            "SELECT alias_name FROM star_aliases WHERE star_id = ? ORDER BY alias_name",
            (star_id,)
        ) as cursor:
            rows = await cursor.fetchall()
            return [row["alias_name"] for row in rows]


async def star_aliases_map(star_ids: list[int]) -> dict[int, list[str]]:
    """Returns the alternate names of several stars in a single query, keyed
    by star id (a star without alias is absent)."""
    if not star_ids:
        return {}
    placeholders = ",".join("?" * len(star_ids))
    async with aiosqlite.connect(TARGETS_DB_PATH, timeout=30.0) as db:
        async with db.execute(
            f"SELECT star_id, alias_name FROM star_aliases WHERE star_id IN ({placeholders}) "
            f"ORDER BY alias_name",
            list(star_ids)
        ) as cursor:
            rows = await cursor.fetchall()
    aliases: dict[int, list[str]] = {}
    for star_id, alias_name in rows:
        aliases.setdefault(star_id, []).append(alias_name)
    return aliases



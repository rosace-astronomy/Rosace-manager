# ─────────────────────────────────────────────────────────────
# Program ↔ star links
# ─────────────────────────────────────────────────────────────

async def program_add_star(program_id: int, star_id: int, exposure_time: Optional[float] = None) -> None:
    """Links a star to a program, with an optional exposure time specific to
    this program/star pair. A second call on the same pair updates the
    exposure time (upsert)."""
    async with aiosqlite.connect(TARGETS_DB_PATH, timeout=30.0) as db:
        await db.execute(
            """INSERT INTO program_stars (program_id, star_id, exposure_time)
               VALUES (?, ?, ?)
               ON CONFLICT (program_id, star_id)
               DO UPDATE SET exposure_time = excluded.exposure_time""",
            (program_id, star_id, exposure_time)
        )
        await db.commit()
    log.info(f"[TARGETS DB] Star {star_id} added to program {program_id} (exposure_time={exposure_time})")


async def program_remove_star(program_id: int, star_id: int) -> None:
    """Removes a star from a program."""
    async with aiosqlite.connect(TARGETS_DB_PATH, timeout=30.0) as db:
        await db.execute(
            "DELETE FROM program_stars WHERE program_id = ? AND star_id = ?",
            (program_id, star_id)
        )
        await db.commit()
    log.info(f"[TARGETS DB] Star {star_id} removed from program {program_id}")


async def program_get_stars(program_id: int) -> list[StarInProgram]:
    """Returns all of a program's stars, with their exposure time,
    optionally specific to this program."""
    async with aiosqlite.connect(TARGETS_DB_PATH, timeout=30.0) as db:
        db.row_factory = aiosqlite.Row
        async with db.execute(
            """SELECT s.*, ps.exposure_time AS exposure_time FROM stars s
               JOIN program_stars ps ON ps.star_id = s.id
               WHERE ps.program_id = ?
               ORDER BY s.name""",
            (program_id,)
        ) as cursor:
            rows = await cursor.fetchall()
            return [StarInProgram(**dict(row)) for row in rows]


async def star_get_programs(star_id: int) -> list[Program]:
    """Returns every program a star belongs to."""
    async with aiosqlite.connect(TARGETS_DB_PATH, timeout=30.0) as db:
        db.row_factory = aiosqlite.Row
        async with db.execute(
            """SELECT p.* FROM programs p
               JOIN program_stars ps ON ps.program_id = p.id
               WHERE ps.star_id = ?
               ORDER BY p.name""",
            (star_id,)
        ) as cursor:
            rows = await cursor.fetchall()
            return [Program(**dict(row)) for row in rows]
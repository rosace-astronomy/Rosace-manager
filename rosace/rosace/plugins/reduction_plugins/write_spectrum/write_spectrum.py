"""
REDUCTION sub-plugin — Final spectrum writing
Writes the final 1D FITS spectrum, its header rebuilt with every keyword the BeSS specification asks for.

Input: crop_target_spectrum. Output: "<final name>.fits" in the session
directory (reduction_helpers.final_name(): the observation file's name plus
the observation ID), under the shared key final_spectrum. No casier.

The header is rebuilt from scratch rather than cleaned: only the cards below
are written, ASCII only, in English, so none of the camera's or the 2D
frame's cards survive.
- Target, under both forms BeSS accepts, so the file stands on its own:
  OBJNAME (the queried name) and RA/DEC/EQUINOX (the catalogue position, in
  degrees, J2000); optional BSS_VMAG (catalogue magnitude) and BSS_STYP
  (spectral type, read from targets.db when known).
- Times: DATE-OBS, DATE-END, EXPTIME (whole observation, as BeSS defines it),
  EXPTIME2 (the exposures summed), JD-OBS and JD-MID (Julian dates of the
  start and of the middle of the observation).
- Observer, site and equipment, from the configuration's observatory block (the BeSS
  forms' names, shared with export_demetra) and the Core site coordinates:
  OBSERVER, BSS_SITE and BSS_LAT/BSS_LONG/BSS_ELEV (both forms), BSS_INST and
  TELESCOP/INSTRUME/DETNAM (both forms), BSS_ITRP when resolving_power is set
  (the instrument's typical value).
- Resolving power measured on the lamp (dispersion_law, read from the
  dispersion law file, shared key dispersion_law_file): BSS_ESRP and the
  wavelength it is given at, BSS_SRPW, in the unit of CUNIT1. Absent when the
  law holds none (not measured, or a law written before it was).
- Signal-to-noise ratio (snr, shared key spectrum_snr), not BeSS keywords
  (BeSS keeps them without using them): SNR1 with its zone SNR1LO-SNR1HI (in
  the unit of CUNIT1), SNR2..., one per measured zone. Absent when not
  measured.
  Giving both forms makes BeSS issue a warning, not a rejection.
- Wavelength axis: CRVAL1, CDELT1, CRPIX1, CTYPE1, CUNIT1.
- Processing: BSS_VHEL = 0 and BSS_TELL/BSS_COSM/BSS_NORM = 'none' (no
  heliocentric, telluric, cosmic-ray or continuum correction; the scaling is
  a plain factor, not a normalization).
- CCD-TEMP when known, SWCREATE (Rosace and its version), and the processing
  COMMENT lines collected by the earlier steps (generic lines inherited from
  the camera dropped).

An observer, site or equipment name missing from the configuration, a text
longer than BeSS's 40 characters, or a non-ASCII character is an error that
stops the reduction.

Once written, the spectrum is shown on the GUI's "Spectre 1D" panel
(reduction_helpers.publish_spectrum_preview()) -- a display for the observer,
not processing: a failure there is only a warning.
"""

from __future__ import annotations

DISPLAY_NAME = "FITS 1D"

import logging
from importlib import metadata
from pathlib import Path

import numpy as np
from astropy.io import fits
from astropy.time import Time

from ....config import OBSERVATORY, SITE_ELEVATION_M, SITE_LATITUDE_DEG, SITE_LONGITUDE_DEG
from ....models import Observation
from ....targets import star_get_by_name
from ...sub_plugin_base import SubPlugin
from ..reduction_helpers import final_name, find_shared_input, publish_spectrum_preview, read_law

log = logging.getLogger("spectro.subplugin.write_spectrum")

BESS_MAX_TEXT = 40
# Generic COMMENT lines a camera driver writes, meaningless in the final spectrum
INHERITED_COMMENTS = ("Flexible Image Transport System", "Astrophysics', volume", "Generated by INDI")


def _text(value: str, keyword: str, limit: int | None = BESS_MAX_TEXT) -> str:
    value = str(value)
    if not value.isascii():
        raise RuntimeError(f"WRITE_SPECTRUM: {keyword} {value!r} has a non-ASCII character")
    if limit and len(value) > limit:
        raise RuntimeError(f"WRITE_SPECTRUM: {keyword} {value!r} is longer than {limit} characters")
    return value


def _software() -> str:
    try:
        return f"Rosace {metadata.version('rosace')}"
    except metadata.PackageNotFoundError:
        return "Rosace"


def _target_field(target, name: str):
    return target.get(name) if isinstance(target, dict) else getattr(target, name, None)


async def _spectral_type(*names: str | None) -> str | None:
    """Spectral type from targets.db, trying each name; None when unknown or
    when the catalogue can't be read (the keyword is optional)."""
    for name in names:
        if not name:
            continue
        try:
            star = await star_get_by_name(name)
        except Exception as error:
            log.debug(f"[WRITE_SPECTRUM] Spectral type lookup failed for {name!r}: {error}")
            return None
        if star is not None:
            return star.spectral_type or None
    return None


def _measured_resolving_power(obs: Observation, session_dir: Path) -> tuple[float, float] | None:
    """(R, wavelength) from the dispersion law file; None when there is no
    law or it holds no resolving power (the keywords are optional)."""
    try:
        law_path = session_dir / find_shared_input(obs, "dispersion_law_file")
    except RuntimeError:
        return None
    if not law_path.exists():
        return None
    law = read_law(law_path)
    if law["resolving_power"] is None or law["resolving_power_wavelength"] is None:
        return None
    return float(law["resolving_power"]), float(law["resolving_power_wavelength"])


def _spectrum_snr(obs: Observation) -> list[dict]:
    """The measured SNR zones (shared key spectrum_snr); empty when not measured."""
    try:
        return list(find_shared_input(obs, "spectrum_snr"))
    except RuntimeError:
        return []


class WriteSpectrumPlugin(SubPlugin):
    """Writes the final 1D FITS spectrum, its header rebuilt with every keyword the BeSS specification asks for."""

    async def execute(self, obs: Observation) -> Observation:
        site = OBSERVATORY
        for key in ("observer", "site", "equipment"):
            if not site.get(key):
                raise RuntimeError(f"WRITE_SPECTRUM: observatory.{key} is not set in the configuration")
        target = obs.scheduler_data.get("target")
        if target is None:
            raise RuntimeError("WRITE_SPECTRUM: no target in scheduler_data")
        object_name = obs.scheduler_data.get("queried_name") or _target_field(target, "name")

        session_dir = Path(obs.obs_dir or "")
        source = find_shared_input(obs, "crop_target_spectrum")
        data, old = fits.getdata(session_dir / source, header=True)
        for key in ("DATE-OBS", "DATE-END", "EXPTIME", "CRVAL1", "CDELT1"):
            if key not in old:
                raise RuntimeError(f"WRITE_SPECTRUM: {key} missing from {source}")
        start = Time(old["DATE-OBS"], format="isot", scale="utc")
        end = Time(old["DATE-END"], format="isot", scale="utc")

        h = fits.Header()
        h["OBJNAME"] = (_text(object_name, "OBJNAME"), "Object name")
        h["RA"] = (round(float(_target_field(target, "ra")), 6), "[deg] Object right ascension, J2000")
        h["DEC"] = (round(float(_target_field(target, "dec")), 6), "[deg] Object declination, J2000")
        h["EQUINOX"] = (2000.0, "Equinox of RA and DEC")
        magnitude = _target_field(target, "magnitude_v")
        if magnitude is not None:
            h["BSS_VMAG"] = (float(magnitude), "Object V magnitude")
        spectral_type = await _spectral_type(_target_field(target, "name"), object_name)
        if spectral_type:
            h["BSS_STYP"] = (_text(spectral_type, "BSS_STYP", limit=None), "Object spectral type")

        h["DATE-OBS"] = (old["DATE-OBS"], "UTC start of the first exposure")
        h["DATE-END"] = (old["DATE-END"], "UTC end of the last exposure")
        h["EXPTIME"] = (float(old["EXPTIME"]), "[s] Total observation duration")
        if "EXPTIME2" in old:
            h["EXPTIME2"] = (old["EXPTIME2"], "Exposures summed")
        h["JD-OBS"] = (round(start.jd, 6), "Julian date of the observation start")
        h["JD-MID"] = (round((start + (end - start) / 2).jd, 6), "Julian date of the observation middle")

        h["OBSERVER"] = (_text(site["observer"], "OBSERVER", limit=None), "Observer")
        h["BSS_SITE"] = (_text(site["site"], "BSS_SITE"), "Observation site")
        h["BSS_LAT"] = (float(SITE_LATITUDE_DEG), "[deg] Site latitude")
        h["BSS_LONG"] = (float(SITE_LONGITUDE_DEG) % 360.0, "[deg] Site longitude, east, 0-360")
        h["BSS_ELEV"] = (float(SITE_ELEVATION_M), "[m] Site elevation")
        h["BSS_INST"] = (_text(site["equipment"], "BSS_INST"), "Equipment")
        for keyword, key, comment in (("TELESCOP", "telescope", "Telescope"),
                                      ("INSTRUME", "spectrograph", "Spectrograph"),
                                      ("DETNAM", "camera", "Camera")):
            if site.get(key):
                h[keyword] = (_text(site[key], keyword), comment)
        if site.get("resolving_power"):
            h["BSS_ITRP"] = (float(site["resolving_power"]), "Instrument typical resolving power")
        measured = _measured_resolving_power(obs, session_dir)
        if measured is not None:
            h["BSS_ESRP"] = (measured[0], "Effective spectral resolving power")
            h["BSS_SRPW"] = (measured[1], "Wavelength of the resolving power")
        for k, zone in enumerate(_spectrum_snr(obs), start=1):
            h[f"SNR{k}"] = (float(zone["snr"]), "DER_SNR, stacked spectrum before resampling")
            h[f"SNR{k}LO"] = (float(zone["wavelength_min"]), f"Start of the SNR{k} zone")
            h[f"SNR{k}HI"] = (float(zone["wavelength_max"]), f"End of the SNR{k} zone")

        h["CRVAL1"] = (float(old["CRVAL1"]), "Wavelength of the reference point")
        h["CDELT1"] = (float(old["CDELT1"]), "Wavelength step")
        h["CRPIX1"] = (float(old.get("CRPIX1", 1)), "Reference point")
        h["CTYPE1"] = ("Wavelength", "Axis type")
        h["CUNIT1"] = (old.get("CUNIT1", "Angstrom"), "Wavelength unit")

        h["BSS_VHEL"] = (0.0, "[km/s] Heliocentric correction applied: none")
        h["BSS_TELL"] = ("none", "Telluric correction")
        h["BSS_COSM"] = ("none", "Cosmic-ray correction")
        h["BSS_NORM"] = ("none", "Continuum normalization")

        if "CCD-TEMP" in old:
            h["CCD-TEMP"] = (float(old["CCD-TEMP"]), "[C] Camera sensor temperature")
        h["SWCREATE"] = (_software(), "Software that produced this file")
        for line in old.get("COMMENT", []):
            text = str(line).strip()
            if text and not any(marker in text for marker in INHERITED_COMMENTS):
                h["COMMENT"] = _text(text, "COMMENT", limit=None)

        name = f"{final_name(obs)}.fits"
        fits.writeto(session_dir / name, np.asarray(data, dtype=np.float32), h, overwrite=True)
        obs.reduction_data["final_spectrum"] = name
        log.info(f"[WRITE_SPECTRUM] Wrote {name} ({data.size} points, {len(h)} header cards)")
        try:
            await publish_spectrum_preview(obs, session_dir / name)
        except Exception as e:
            log.warning(f"[WRITE_SPECTRUM] Could not show the spectrum in the GUI: {e}")
        return obs
